#ifndef COMMON_H
#define COMMON_H

#include <stdint.h>

// ============================================================
// 公共数据类型定义
// 感知模块(A)输出 → 决策模块(B)输入，靠这些结构体传数据。
// ============================================================


// ------------------------------------------------------------
// Direction — 方向索引
// 左/中/右，值为 0/1/2，直接当数组下标用（zones[LEFT]）。
// ------------------------------------------------------------
enum Direction {
    LEFT   = 0,
    CENTER = 1,
    RIGHT  = 2
};


// ------------------------------------------------------------
// RiskLevel — 风险等级
// 决策模块(B)根据距离算出，阈值在 config.h 里：
//   <400mm  → DANGER
//   <800mm  → WARN
//   <1200mm → NOTICE
//   ≥1200mm → SAFE
// ------------------------------------------------------------
enum RiskLevel {
    SAFE   = 0,  // 安全，不需要震动
    NOTICE = 1,  // 注意，慢节奏提醒
    WARN   = 2,  // 警告，中节奏提醒
    DANGER = 3   // 危险，快节奏强提醒
};


// ------------------------------------------------------------
// ZoneState — 单个方向的感知数据（决策模块B只需要这两个字段）
//
// distanceMm — 你拿来判断危险等级的数据
// valid      — 传感器是否正常（true=有数据，false=断开/超时）
//
// 注意：感知模块内部用的 lastValidMs、滤波缓冲区等不放在这里，
//       决策模块只关心距离和是否有效。
// ------------------------------------------------------------
struct ZoneState {
    uint16_t distanceMm;  // 滤波后的距离（mm）
    bool     valid;       // 传感器是否有效
};


// ------------------------------------------------------------
// SystemState — 感知模块(A)的完整输出，决策模块(B)的输入
//
// zones            — 左/中/右三个方向的距离和有效性，下标用 LEFT/CENTER/RIGHT
// anySensorInvalid — 至少有一个方向失效（true=有传感器不正常）
// allSensorsInvalid — 三个方向全部失效（true=决策模块应不输出任何震动）
// ------------------------------------------------------------
struct SystemState {
    ZoneState zones[3];
    bool      anySensorInvalid;
    bool      allSensorsInvalid;
};


// ------------------------------------------------------------
// FeedbackDecision — 决策模块(B)的输出
//
// activeDirections — 激活方向位掩码，可同时激活多个方向：
//                    bit0(1<<LEFT)=左, bit1(1<<CENTER)=中, bit2(1<<RIGHT)=右
//                    0 表示不需要震动
// risk             — 最终风险等级（带滞回，决定震动节奏）
// isWideObstacle   — 大范围障碍（左右距离差≤120mm且都有障碍），true=左右同时震
// ------------------------------------------------------------
struct FeedbackDecision {
    uint8_t   activeDirections;
    RiskLevel risk;
    bool      isWideObstacle;
};


#endif // COMMON_H
